-- 03: internal stages, file formats and the RAW tables.
-- Run once as LOADER after 02_roles_and_users.sql.
--
-- The legacy file format matches the extracts: semicolon separated, Latin-1,
-- a header line, empty fields for nulls, and a trailer line with the row count.
-- The trailer has two fields instead of a full record, so COPY INTO rejects it
-- and the loader records one rejected row per file, which is expected.

USE ROLE LOADER;
USE WAREHOUSE LOAD_WH;
USE SCHEMA LATE_DATA_LAB.RAW;

CREATE FILE FORMAT IF NOT EXISTS LEGACY_CSV
    TYPE = CSV
    FIELD_DELIMITER = ';'
    SKIP_HEADER = 1
    ENCODING = 'ISO88591'
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('')
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
    TRIM_SPACE = FALSE
    COMPRESSION = AUTO
    COMMENT = 'Legacy core-system extracts';

CREATE FILE FORMAT IF NOT EXISTS FX_CSV
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    ENCODING = 'UTF8'
    EMPTY_FIELD_AS_NULL = TRUE
    COMPRESSION = AUTO
    COMMENT = 'Cached Norges Bank exchange rates';

CREATE STAGE IF NOT EXISTS LEGACY_STAGE
    FILE_FORMAT = LEGACY_CSV
    COMMENT = 'Daily legacy extracts, one folder per extract day (YYYYMMDD)';

CREATE STAGE IF NOT EXISTS FX_STAGE
    FILE_FORMAT = FX_CSV
    COMMENT = 'Exchange-rate cache';

-- RAW keeps the files as delivered: every column text, plus where the row came from.
CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CUST_ID VARCHAR, CUST_NO VARCHAR, FIRST_NM VARCHAR, LAST_NM VARCHAR, BIRTH_DT VARCHAR,
    SEGM VARCHAR, REGION VARCHAR, STREET VARCHAR, POST_CD VARCHAR, CITY VARCHAR,
    CUST_SINCE VARCHAR, CRT_TS VARCHAR, UPD_TS VARCHAR,
    _FILE_NAME VARCHAR NOT NULL, _EXTRACT_DAY DATE NOT NULL, _LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS ACCOUNTS (
    ACCT_NO VARCHAR, CUST_ID VARCHAR, ACCT_TYP VARCHAR, OPEN_DT VARCHAR, CLOSE_DT VARCHAR,
    STAT VARCHAR, OPEN_BAL VARCHAR, CR_LIM VARCHAR, CRT_TS VARCHAR, UPD_TS VARCHAR,
    _FILE_NAME VARCHAR NOT NULL, _EXTRACT_DAY DATE NOT NULL, _LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS CARDS (
    CARD_ID VARCHAR, ACCT_NO VARCHAR, PAN_MASK VARCHAR, ISSUE_DT VARCHAR, EXP_DT VARCHAR,
    STAT VARCHAR, CRT_TS VARCHAR, UPD_TS VARCHAR,
    _FILE_NAME VARCHAR NOT NULL, _EXTRACT_DAY DATE NOT NULL, _LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS MERCHANTS (
    MERCH_ID VARCHAR, MERCH_NM VARCHAR, CAT_CD VARCHAR, CAT_NM VARCHAR, CTRY VARCHAR, CITY VARCHAR,
    CRT_TS VARCHAR, UPD_TS VARCHAR,
    _FILE_NAME VARCHAR NOT NULL, _EXTRACT_DAY DATE NOT NULL, _LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS TRANSACTIONS (
    TXN_ID VARCHAR, ACCT_NO VARCHAR, CARD_ID VARCHAR, MERCH_ID VARCHAR, TXN_TYP VARCHAR,
    BOOK_DT VARCHAR, AMT VARCHAR, CCY VARCHAR, STAT VARCHAR, REV_OF VARCHAR, CRT_TS VARCHAR, UPD_TS VARCHAR,
    _FILE_NAME VARCHAR NOT NULL, _EXTRACT_DAY DATE NOT NULL, _LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS FX_RATES (
    RATE_DATE VARCHAR, CURRENCY VARCHAR, RATE_NOK VARCHAR,
    _FILE_NAME VARCHAR NOT NULL, _EXTRACT_DAY DATE NOT NULL, _LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS LOAD_AUDIT (
    FILE_NAME      VARCHAR NOT NULL,
    ENTITY         VARCHAR NOT NULL,
    EXTRACT_DAY    DATE NOT NULL,
    FILE_HASH      VARCHAR NOT NULL,
    ROWS_IN_FILE   INTEGER,
    ROWS_LOADED    INTEGER NOT NULL,
    ROWS_REJECTED  INTEGER NOT NULL,
    STATUS         VARCHAR NOT NULL,
    ERROR_MESSAGE  VARCHAR,
    LOADED_AT      TIMESTAMP_NTZ NOT NULL
);

