-- 02: roles, grants and the service user.
-- Run once as ACCOUNTADMIN after 01_account_setup.sql.
--
-- Three functional roles, each limited to one layer:
--   LOADER       writes RAW (stage, file formats, COPY INTO), uses LOAD_WH
--   TRANSFORMER  reads RAW, owns STAGING and MARTS (dbt), uses TRANSFORM_WH
--   REPORTER     reads MARTS only (Power BI, ad hoc), uses TRANSFORM_WH
-- plus one regional reporting role per region that the row access policy restricts.
--
-- Replace <RSA_PUBLIC_KEY> with the key printed by: python snowflake/make_keypair.py
-- Replace <YOUR_USER> with your own login name.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS LOADER      COMMENT = 'Writes the RAW layer';
CREATE ROLE IF NOT EXISTS TRANSFORMER COMMENT = 'Builds STAGING and MARTS with dbt';
CREATE ROLE IF NOT EXISTS REPORTER    COMMENT = 'Reads MARTS';

-- Keep the custom roles under SYSADMIN so administrators inherit them.
GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE REPORTER    TO ROLE SYSADMIN;

-- Warehouses: USAGE runs queries, OPERATE lets the role resume a suspended warehouse.
GRANT USAGE, OPERATE ON WAREHOUSE LOAD_WH      TO ROLE LOADER;
GRANT USAGE, OPERATE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER;
GRANT USAGE          ON WAREHOUSE TRANSFORM_WH TO ROLE REPORTER;

-- Database and schemas.
GRANT USAGE ON DATABASE LATE_DATA_LAB TO ROLE LOADER;
GRANT USAGE ON DATABASE LATE_DATA_LAB TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE LATE_DATA_LAB TO ROLE REPORTER;

GRANT OWNERSHIP ON SCHEMA LATE_DATA_LAB.RAW     TO ROLE LOADER      COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA LATE_DATA_LAB.STAGING TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA LATE_DATA_LAB.MARTS   TO ROLE TRANSFORMER COPY CURRENT GRANTS;

-- TRANSFORMER reads RAW, now and for tables created later.
GRANT USAGE  ON SCHEMA LATE_DATA_LAB.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES    IN SCHEMA LATE_DATA_LAB.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LATE_DATA_LAB.RAW TO ROLE TRANSFORMER;

-- REPORTER reads MARTS only.
GRANT USAGE  ON SCHEMA LATE_DATA_LAB.MARTS TO ROLE REPORTER;
GRANT SELECT ON ALL TABLES    IN SCHEMA LATE_DATA_LAB.MARTS TO ROLE REPORTER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA LATE_DATA_LAB.MARTS TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LATE_DATA_LAB.MARTS TO ROLE REPORTER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA LATE_DATA_LAB.MARTS TO ROLE REPORTER;

-- Regional reporting roles: same read access, restricted by the row access policy in 04.
CREATE ROLE IF NOT EXISTS REPORTER_VESTLAND COMMENT = 'Regional manager, Vestland';
CREATE ROLE IF NOT EXISTS REPORTER_OSLO     COMMENT = 'Regional manager, Oslo';
GRANT ROLE REPORTER TO ROLE REPORTER_VESTLAND;
GRANT ROLE REPORTER TO ROLE REPORTER_OSLO;
GRANT ROLE REPORTER_VESTLAND TO ROLE SYSADMIN;
GRANT ROLE REPORTER_OSLO     TO ROLE SYSADMIN;

-- The row access policy lives in MARTS and is attached by dbt after each build.
GRANT CREATE ROW ACCESS POLICY ON SCHEMA LATE_DATA_LAB.MARTS TO ROLE TRANSFORMER;
GRANT APPLY ROW ACCESS POLICY ON ACCOUNT TO ROLE TRANSFORMER;

-- The experiment gives every strategy run its own STAGING__x and MARTS__x schemas on this database.
GRANT CREATE SCHEMA ON DATABASE LATE_DATA_LAB TO ROLE TRANSFORMER;

-- Cost figures are read from the account usage views.
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE TRANSFORMER;

-- Service user for the loader and dbt: key-pair authentication, no password, no interactive login.
CREATE USER IF NOT EXISTS LDL_SVC
    TYPE = SERVICE
    DEFAULT_ROLE = TRANSFORMER
    DEFAULT_WAREHOUSE = TRANSFORM_WH
    DEFAULT_NAMESPACE = LATE_DATA_LAB.STAGING
    COMMENT = 'Service user for the loader (LOADER) and dbt (TRANSFORMER)';
ALTER USER LDL_SVC SET RSA_PUBLIC_KEY = '<RSA_PUBLIC_KEY>';
-- The experiment measures real work: no result cache for this user, in every session and thread.
ALTER USER LDL_SVC SET USE_CACHED_RESULT = FALSE;
GRANT ROLE LOADER      TO USER LDL_SVC;
GRANT ROLE TRANSFORMER TO USER LDL_SVC;

-- Your own user gets the reporting roles for checking the policy with different roles in Snowsight.
GRANT ROLE REPORTER          TO USER "<YOUR_USER>";
GRANT ROLE REPORTER_VESTLAND TO USER "<YOUR_USER>";
GRANT ROLE REPORTER_OSLO     TO USER "<YOUR_USER>";

-- Reporting service user for Power BI Desktop: the connector signs in with a key pair, not with
-- SSO or MFA, so the report gets its own read-only user. Same key tool, a second key file.
CREATE USER IF NOT EXISTS LDL_REPORT_SVC
    TYPE = SERVICE
    DEFAULT_ROLE = REPORTER
    DEFAULT_WAREHOUSE = TRANSFORM_WH
    DEFAULT_NAMESPACE = LATE_DATA_LAB.MARTS
    COMMENT = 'Power BI Desktop, read-only on MARTS, key pair';
ALTER USER LDL_REPORT_SVC SET RSA_PUBLIC_KEY = '<REPORT_RSA_PUBLIC_KEY>';
GRANT ROLE REPORTER          TO USER LDL_REPORT_SVC;
GRANT ROLE REPORTER_VESTLAND TO USER LDL_REPORT_SVC;
GRANT ROLE REPORTER_OSLO     TO USER LDL_REPORT_SVC;

SHOW GRANTS TO USER LDL_SVC;
SHOW GRANTS TO USER LDL_REPORT_SVC;
